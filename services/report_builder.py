"""Generates downloadable PDF/DOCX inspection reports from real database data.

Called by the Reports page's "Generate Report" action. The report always
contains the employer's actual inspection/violation history and the AI
recommendation computed from that employer's own data - never placeholder
text.
"""
from __future__ import annotations

from datetime import datetime
from pathlib import Path

from docx import Document
from docx.shared import Pt, RGBColor
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.platypus import (
    ListFlowable, ListItem, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle,
)

REPORTS_DIR = Path(__file__).resolve().parent.parent / "generated_reports"
REPORTS_DIR.mkdir(exist_ok=True)


def _report_context(employer, violations, inspections, recommendation: dict) -> dict:
    return {
        "employer_name": employer.name,
        "company_name": employer.name,
        "sector": employer.sector or "-",
        "dzongkhag": employer.dzongkhag or "-",
        "location": employer.location or "-",
        "risk_category": employer.risk_category or "Low",
        "final_risk_score": employer.final_risk_score or 0,
        "last_inspection_date": str(employer.last_inspection_date) if employer.last_inspection_date else "Not yet inspected",
        "total_inspections": employer.total_inspections or 0,
        "improvement_notices": employer.improvement_notices or 0,
        "penalty_memos": employer.penalty_memos or 0,
        "total_penalty_amount": employer.total_penalty_amount or 0.0,
        "violations": violations,
        "inspections": inspections,
        "osh_findings": [v for v in violations if v.is_osh],
        "recommendation": recommendation,
        "report_date": datetime.now().strftime("%d %B %Y"),
    }


def generate_pdf(report_code: str, employer, violations, inspections, recommendation: dict) -> str:
    ctx = _report_context(employer, violations, inspections, recommendation)
    filename = f"{report_code}.pdf"
    path = REPORTS_DIR / filename

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle("LirasTitle", parent=styles["Title"], textColor=colors.HexColor("#12355B"))
    h2 = ParagraphStyle("LirasH2", parent=styles["Heading2"], textColor=colors.HexColor("#12355B"), spaceBefore=14)
    body = styles["BodyText"]

    doc = SimpleDocTemplate(str(path), pagesize=A4, topMargin=1.8 * cm, bottomMargin=1.8 * cm)
    story = []

    story.append(Paragraph(f"Labour Inspection Report - {report_code}", title_style))
    story.append(Paragraph(f"Generated by ALIRAS/LIRAS on {ctx['report_date']}", body))
    story.append(Spacer(1, 14))

    story.append(Paragraph("Employer Details", h2))
    emp_table = Table([
        ["Employer Name", ctx["employer_name"]],
        ["Company Name", ctx["company_name"]],
        ["Industry / Sector", ctx["sector"]],
        ["Dzongkhag", ctx["dzongkhag"]],
        ["Location", ctx["location"]],
        ["Risk Level", ctx["risk_category"]],
        ["Risk Score", f"{ctx['final_risk_score']:.1f} / 100"],
    ], colWidths=[5 * cm, 10 * cm])
    emp_table.setStyle(TableStyle([
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("TEXTCOLOR", (0, 0), (0, -1), colors.HexColor("#12355B")),
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#d0d7de")),
    ]))
    story.append(emp_table)

    story.append(Paragraph("Inspection Details", h2))
    story.append(Paragraph(
        f"Total inspections on record: {ctx['total_inspections']} &nbsp;|&nbsp; "
        f"Last inspection: {ctx['last_inspection_date']} &nbsp;|&nbsp; "
        f"Improvement notices: {ctx['improvement_notices']} &nbsp;|&nbsp; "
        f"Penalty memos: {ctx['penalty_memos']}", body))
    if ctx["inspections"]:
        rows = [["Date", "Type", "Inspector", "Status"]]
        for i in ctx["inspections"][:10]:
            rows.append([str(i.inspection_date or "-"), i.inspection_type or "-", i.inspector or "-", i.status or "-"])
        insp_table = Table(rows, colWidths=[3 * cm, 5 * cm, 4 * cm, 3 * cm])
        insp_table.setStyle(TableStyle([
            ("FONTSIZE", (0, 0), (-1, -1), 8.5),
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#12355B")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#d0d7de")),
        ]))
        story.append(Spacer(1, 6))
        story.append(insp_table)
    else:
        story.append(Paragraph("No prior inspection history on record.", body))

    story.append(Paragraph("Violations & OSH Findings", h2))
    if ctx["violations"]:
        rows = [["Date", "Type", "Contravention", "Amount (Nu.)"]]
        for v in ctx["violations"][:10]:
            rows.append([str(v.inspection_date or "-"), v.notice_type or "-",
                         (v.contravention or v.particulars or "-")[:60], f"{v.amount:,.0f}" if v.amount else "-"])
        vio_table = Table(rows, colWidths=[2.5 * cm, 3.5 * cm, 6.5 * cm, 2.5 * cm])
        vio_table.setStyle(TableStyle([
            ("FONTSIZE", (0, 0), (-1, -1), 8.5),
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#12355B")),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
            ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#d0d7de")),
        ]))
        story.append(Spacer(1, 6))
        story.append(vio_table)
    else:
        story.append(Paragraph("No violations on record.", body))

    story.append(Paragraph("AI Recommendation", h2))
    rec = ctx["recommendation"]
    story.append(Paragraph(f"<b>Inspection priority:</b> {rec['inspection_priority']}", body))
    story.append(Paragraph(f"<b>Summary:</b> {rec['summary']}", body))
    story.append(Paragraph(f"<b>Recommended follow-up date:</b> {rec['recommended_follow_up_date']}", body))
    story.append(Paragraph("<b>Risk explanation:</b>", body))
    story.append(ListFlowable([ListItem(Paragraph(x, body)) for x in rec["risk_explanation"]], bulletType="bullet"))
    story.append(Paragraph("<b>Required corrective actions:</b>", body))
    story.append(ListFlowable([ListItem(Paragraph(x, body)) for x in rec["required_corrective_actions"]], bulletType="bullet"))
    story.append(Paragraph("<b>Suggested enforcement actions:</b>", body))
    story.append(ListFlowable([ListItem(Paragraph(x, body)) for x in rec["suggested_enforcement_actions"]], bulletType="bullet"))
    story.append(Paragraph("<b>Compliance improvement recommendations:</b>", body))
    story.append(ListFlowable([ListItem(Paragraph(x, body)) for x in rec["compliance_improvement_recommendations"]], bulletType="bullet"))

    story.append(Paragraph("Summary & Conclusion", h2))
    story.append(Paragraph(
        f"{ctx['employer_name']} is currently classified as <b>{ctx['risk_category']} risk</b> "
        f"with a combined statistical/AI risk score of {ctx['final_risk_score']:.1f}/100, based on "
        f"{ctx['total_inspections']} recorded inspection(s), {ctx['improvement_notices']} improvement "
        f"notice(s) and {ctx['penalty_memos']} penalty memo(s). {rec['summary']}", body))

    doc.build(story)
    return str(path)


def generate_docx(report_code: str, employer, violations, inspections, recommendation: dict) -> str:
    ctx = _report_context(employer, violations, inspections, recommendation)
    filename = f"{report_code}.docx"
    path = REPORTS_DIR / filename

    doc = Document()

    title = doc.add_heading(f"Labour Inspection Report - {report_code}", level=0)
    title.runs[0].font.color.rgb = RGBColor(0x12, 0x35, 0x5B)
    doc.add_paragraph(f"Generated by ALIRAS/LIRAS on {ctx['report_date']}")

    doc.add_heading("Employer Details", level=1)
    table = doc.add_table(rows=0, cols=2)
    table.style = "Light Grid Accent 1"
    for label, value in [
        ("Employer Name", ctx["employer_name"]),
        ("Company Name", ctx["company_name"]),
        ("Industry / Sector", ctx["sector"]),
        ("Dzongkhag", ctx["dzongkhag"]),
        ("Location", ctx["location"]),
        ("Risk Level", ctx["risk_category"]),
        ("Risk Score", f"{ctx['final_risk_score']:.1f} / 100"),
    ]:
        row = table.add_row().cells
        row[0].text = label
        row[1].text = str(value)

    doc.add_heading("Inspection Details", level=1)
    doc.add_paragraph(
        f"Total inspections on record: {ctx['total_inspections']} | "
        f"Last inspection: {ctx['last_inspection_date']} | "
        f"Improvement notices: {ctx['improvement_notices']} | "
        f"Penalty memos: {ctx['penalty_memos']}"
    )
    if ctx["inspections"]:
        t = doc.add_table(rows=1, cols=4)
        t.style = "Light Grid Accent 1"
        hdr = t.rows[0].cells
        hdr[0].text, hdr[1].text, hdr[2].text, hdr[3].text = "Date", "Type", "Inspector", "Status"
        for i in ctx["inspections"][:10]:
            cells = t.add_row().cells
            cells[0].text = str(i.inspection_date or "-")
            cells[1].text = i.inspection_type or "-"
            cells[2].text = i.inspector or "-"
            cells[3].text = i.status or "-"
    else:
        doc.add_paragraph("No prior inspection history on record.")

    doc.add_heading("Violations & OSH Findings", level=1)
    if ctx["violations"]:
        t = doc.add_table(rows=1, cols=4)
        t.style = "Light Grid Accent 1"
        hdr = t.rows[0].cells
        hdr[0].text, hdr[1].text, hdr[2].text, hdr[3].text = "Date", "Type", "Contravention", "Amount (Nu.)"
        for v in ctx["violations"][:10]:
            cells = t.add_row().cells
            cells[0].text = str(v.inspection_date or "-")
            cells[1].text = v.notice_type or "-"
            cells[2].text = (v.contravention or v.particulars or "-")
            cells[3].text = f"{v.amount:,.0f}" if v.amount else "-"
    else:
        doc.add_paragraph("No violations on record.")

    doc.add_heading("AI Recommendation", level=1)
    rec = ctx["recommendation"]
    doc.add_paragraph(f"Inspection priority: {rec['inspection_priority']}").runs[0].bold = True
    doc.add_paragraph(f"Summary: {rec['summary']}")
    doc.add_paragraph(f"Recommended follow-up date: {rec['recommended_follow_up_date']}")
    doc.add_paragraph("Risk explanation:").runs[0].bold = True
    for x in rec["risk_explanation"]:
        doc.add_paragraph(x, style="List Bullet")
    doc.add_paragraph("Required corrective actions:").runs[0].bold = True
    for x in rec["required_corrective_actions"]:
        doc.add_paragraph(x, style="List Bullet")
    doc.add_paragraph("Suggested enforcement actions:").runs[0].bold = True
    for x in rec["suggested_enforcement_actions"]:
        doc.add_paragraph(x, style="List Bullet")
    doc.add_paragraph("Compliance improvement recommendations:").runs[0].bold = True
    for x in rec["compliance_improvement_recommendations"]:
        doc.add_paragraph(x, style="List Bullet")

    doc.add_heading("Summary & Conclusion", level=1)
    doc.add_paragraph(
        f"{ctx['employer_name']} is currently classified as {ctx['risk_category']} risk "
        f"with a combined statistical/AI risk score of {ctx['final_risk_score']:.1f}/100, based on "
        f"{ctx['total_inspections']} recorded inspection(s), {ctx['improvement_notices']} improvement "
        f"notice(s) and {ctx['penalty_memos']} penalty memo(s). {rec['summary']}"
    )

    doc.save(str(path))
    return str(path)
